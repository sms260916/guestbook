"""Supabase PostgreSQL을 사용하는 방명록 웹 서버."""

from dataclasses import dataclass, field
from html import escape
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import os
from pathlib import Path
import psycopg
from urllib.parse import parse_qs, urlsplit

BASE_DIR = Path(__file__).resolve().parent
HTML_PATH = BASE_DIR / "index.html"
MAX_NAME_LENGTH = 40
MAX_MESSAGE_LENGTH = 1000
MAX_FORM_BYTES = 8192
VISIBLE_ENTRY_LIMIT = 50


@dataclass
class GuestbookEntry:
    id: int
    name: str
    message: str
    created_at: str
    parent_id: int | None = None
    replies: list["GuestbookEntry"] = field(default_factory=list)


@dataclass(frozen=True, repr=False)
class DatabaseSettings:
    host: str
    port: int
    dbname: str
    user: str
    password: str
    sslmode: str = "require"

    @classmethod
    def from_env(cls):
        keys = ("DB_HOST", "DB_PORT", "DB_NAME", "DB_USER", "DB_PASSWORD")
        missing = [key for key in keys if not os.environ.get(key)]
        if missing:
            raise ValueError("필수 환경 변수 누락: " + ", ".join(missing))
        try:
            port = int(os.environ["DB_PORT"])
        except ValueError:
            raise ValueError("DB_PORT는 정수여야 합니다.") from None
        if not 1 <= port <= 65535:
            raise ValueError("DB_PORT는 1~65535 범위여야 합니다.")
        sslmode = os.environ.get("DB_SSLMODE", "require")
        if sslmode not in ("require", "verify-ca", "verify-full"):
            raise ValueError("DB_SSLMODE는 require, verify-ca, verify-full 중 하나여야 합니다.")
        return cls(*(os.environ[key] if key != "DB_PORT" else port for key in keys),
                   sslmode=sslmode)


def connect_database(settings: DatabaseSettings):
    # 개별 인자로 전달하므로 비밀번호의 특수문자를 URL 인코딩할 필요가 없다.
    return psycopg.connect(
        host=settings.host, port=settings.port, dbname=settings.dbname,
        user=settings.user, password=settings.password, sslmode=settings.sslmode,
        connect_timeout=10, prepare_threshold=None,
    )


def initialize_database(settings: DatabaseSettings) -> None:
    """원글/댓글 구조와 UTC 시각 문자열을 유지한다. 실패 시 전체 롤백한다."""
    with connect_database(settings) as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS guestbook_entries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                message TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT
                    to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
                parent_id BIGINT REFERENCES guestbook_entries(id)
                    DEFERRABLE INITIALLY DEFERRED
            )
            """
        )
        connection.execute(
            "ALTER TABLE guestbook_entries ADD COLUMN IF NOT EXISTS "
            "parent_id BIGINT REFERENCES guestbook_entries(id)"
        )
        connection.execute(
            "CREATE INDEX IF NOT EXISTS guestbook_entries_parent_id_idx "
            "ON guestbook_entries(parent_id)"
        )


def add_entry(
    settings: DatabaseSettings,
    name: str,
    message: str,
    parent_id: int | None = None,
) -> None:
    """검증된 글이나 원글의 답글을 SQL 매개변수로 저장한다."""
    with connect_database(settings) as connection:
        connection.execute(
            """
            INSERT INTO guestbook_entries (name, message, parent_id)
            VALUES (%s, %s, %s)
            """,
            (name, message, parent_id),
        )


def is_root_entry(settings: DatabaseSettings, entry_id: int) -> bool:
    """대댓글이 아닌 원글인지 확인한다."""
    with connect_database(settings) as connection:
        return (
            connection.execute(
                "SELECT 1 FROM guestbook_entries "
                "WHERE id = %s AND parent_id IS NULL",
                (entry_id,),
            ).fetchone()
            is not None
        )


def get_recent_entries(settings: DatabaseSettings) -> list[GuestbookEntry]:
    """최신 원글 50개와 각 원글의 답글을 읽는다."""
    with connect_database(settings) as connection:
        rows = connection.execute(
            """
            WITH recent_roots AS (
                SELECT id
                FROM guestbook_entries
                WHERE parent_id IS NULL
                ORDER BY id DESC
                LIMIT %s
            )
            SELECT entry.id, entry.name, entry.message, entry.created_at,
                   entry.parent_id, roots.id AS root_id
            FROM recent_roots AS roots
            JOIN guestbook_entries AS entry
              ON entry.id = roots.id OR entry.parent_id = roots.id
            ORDER BY roots.id DESC,
                     CASE WHEN entry.parent_id IS NULL THEN 0 ELSE 1 END,
                     entry.id ASC
            """,
            (VISIBLE_ENTRY_LIMIT,),
        ).fetchall()

    roots: dict[int, GuestbookEntry] = {}
    for entry_id, name, message, created_at, parent_id, root_id in rows:
        if parent_id is None:
            roots[entry_id] = GuestbookEntry(
                entry_id,
                name,
                message,
                created_at,
            )
        else:
            roots[root_id].replies.append(
                GuestbookEntry(entry_id, name, message, created_at, parent_id)
            )
    return list(roots.values())


class GuestbookHTTPServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, address: tuple[str, int], settings: DatabaseSettings) -> None:
        initialize_database(settings)
        self.settings = settings
        super().__init__(address, GuestbookRequestHandler)


class GuestbookRequestHandler(BaseHTTPRequestHandler):
    def do_GET(self) -> None:
        if urlsplit(self.path).path != "/":
            self.send_error(404, "페이지를 찾을 수 없습니다.")
            return

        entries = get_recent_entries(self.server.settings)
        query = parse_qs(urlsplit(self.path).query)
        notice_text = {
            "1": "새 글을 남겼습니다.",
            "reply": "댓글을 남겼습니다.",
        }.get(query.get("saved", [""])[0])
        notice = (
            f'<p class="notice" role="status">{notice_text}</p>'
            if notice_text
            else ""
        )
        self._send_page(200, self._render_page(entries, notice))

    def do_POST(self) -> None:
        if urlsplit(self.path).path != "/":
            self.send_error(404, "페이지를 찾을 수 없습니다.")
            return

        content_type = self.headers.get("Content-Type", "").split(";", 1)[0]
        if content_type.strip().lower() != "application/x-www-form-urlencoded":
            self._show_error(400, "폼 형식의 요청만 받을 수 있습니다.")
            return

        content_length = self.headers.get("Content-Length")
        try:
            body_length = int(content_length or "")
        except ValueError:
            self._show_error(400, "요청 본문 크기를 확인할 수 없습니다.")
            return

        if body_length < 0 or body_length > MAX_FORM_BYTES:
            self._show_error(413, "입력한 내용이 너무 큽니다.")
            return

        try:
            form = parse_qs(
                self.rfile.read(body_length).decode("utf-8"),
                keep_blank_values=True,
            )
        except UnicodeDecodeError:
            self._show_error(400, "입력은 UTF-8 형식이어야 합니다.")
            return

        raw_parent_id = form.get("parent_id", [""])[0].strip()
        parent_id = None
        if raw_parent_id:
            try:
                parent_id = int(raw_parent_id)
            except ValueError:
                self._show_error(400, "답글을 달 글을 확인할 수 없습니다.")
                return
            if parent_id < 1 or not is_root_entry(self.server.settings, parent_id):
                self._show_error(400, "답글은 원글에만 작성할 수 있습니다.")
                return

        name = form.get("name", [""])[0].strip()
        message = form.get("message", [""])[0].strip()
        if not name or len(name) > MAX_NAME_LENGTH:
            self._show_error(400, f"이름은 1~{MAX_NAME_LENGTH}자로 입력해 주세요.")
            return
        if not message or len(message) > MAX_MESSAGE_LENGTH:
            self._show_error(
                400,
                f"내용은 1~{MAX_MESSAGE_LENGTH}자로 입력해 주세요.",
            )
            return

        add_entry(self.server.settings, name, message, parent_id)
        self.send_response(303)
        self.send_header("Location", "/?saved=reply" if parent_id else "/?saved=1")
        self.send_header("Content-Length", "0")
        self.end_headers()

    def _show_error(self, status: int, message: str) -> None:
        error_markup = f'<p class="error" role="alert">{escape(message)}</p>'
        self._send_page(
            status,
            self._render_page(
                get_recent_entries(self.server.settings),
                error_markup,
            ),
        )

    def _render_page(
        self,
        entries: list[GuestbookEntry],
        notice: str,
    ) -> str:
        if entries:
            entry_markup = "\n".join(self._render_entry(entry) for entry in entries)
        else:
            entry_markup = (
                '<p class="empty">아직 등록된 글이 없습니다. '
                "첫 글을 남겨보세요.</p>"
            )

        template = HTML_PATH.read_text(encoding="utf-8")
        return (
            template.replace("{{notice}}", notice)
            .replace("{{entries}}", entry_markup)
        )

    def _render_entry(self, entry: GuestbookEntry) -> str:
        reply_markup = "\n".join(
            (
                '<article class="reply">'
                f'<div class="entry-heading"><h3>{escape(reply.name)}</h3>'
                f'<time datetime="{escape(reply.created_at, quote=True)}">'
                f"{escape(reply.created_at)}</time></div>"
                f'<p class="message">{escape(reply.message)}</p>'
                "</article>"
            )
            for reply in entry.replies
        )
        if not reply_markup:
            reply_markup = '<p class="reply-empty">첫 댓글을 남겨보세요.</p>'

        return (
            '<article class="entry">'
            '<div class="entry-heading">'
            f'<h3>{escape(entry.name)}</h3>'
            f'<time datetime="{escape(entry.created_at, quote=True)}">'
            f"{escape(entry.created_at)}</time>"
            "</div>"
            f'<p class="message">{escape(entry.message)}</p>'
            '<details class="reply-box"><summary>댓글 남기기</summary>'
            '<form method="post" action="/">'
            f'<input type="hidden" name="parent_id" value="{entry.id}">'
            '<label>이름<input name="name" type="text" maxlength="40" required></label>'
            '<label>댓글<textarea name="message" rows="2" maxlength="1000" '
            'required></textarea></label>'
            '<button type="submit">댓글 등록</button>'
            "</form></details>"
            f'<div class="replies" aria-label="댓글">{reply_markup}</div>'
            "</article>"
        )

    def _send_page(self, status: int, content: str) -> None:
        encoded = content.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(encoded)))
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        self.wfile.write(encoded)


def create_server(
    settings: DatabaseSettings | None = None,
    host: str = "127.0.0.1",
    port: int = 8000,
) -> GuestbookHTTPServer:
    """테스트와 실행 코드에서 같은 서버 생성을 사용한다."""
    return GuestbookHTTPServer((host, port), settings or DatabaseSettings.from_env())


def main() -> None:
    settings = DatabaseSettings.from_env()
    host = os.environ.get("HOST", "0.0.0.0")
    port = int(os.environ.get("PORT", "8000"))
    server = create_server(settings, host, port)
    print(f"방명록 서버 실행: http://{host}:{port}")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n방명록 서버를 종료합니다.")
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
